"""
AI Models — Milestone 10.

Persists conversations and messages generated by the LangGraph AI Match Assistant.
Tracks tool calls, citations (sources), token usage, and latency.
"""
import uuid
from django.conf import settings
from django.db import models


class AIConversation(models.Model):
    """
    Groups turns of conversation between a user and the AI assistant for a specific match.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="ai_conversations",
    )
    match = models.ForeignKey(
        "matches.Match",
        on_delete=models.CASCADE,
        related_name="ai_conversations",
    )
    title = models.CharField(max_length=255, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "ai_conversations"
        ordering = ["-updated_at"]
        indexes = [
            models.Index(fields=["user", "match"], name="idx_ai_conv_user_match"),
            models.Index(fields=["updated_at"], name="idx_ai_conv_updated"),
        ]

    def __str__(self) -> str:
        return f"AIConversation {self.id} (Match: {self.match_id})"


class AIMessage(models.Model):
    """
    Individual turn in an AI assistant conversation.
    Records role, text content, tool calls executed, citation sources,
    LLM token consumption, and response latency.
    """

    ROLE_CHOICES = [
        ("user", "User"),
        ("assistant", "Assistant"),
        ("system", "System"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    conversation = models.ForeignKey(
        AIConversation,
        on_delete=models.CASCADE,
        related_name="messages",
    )
    role = models.CharField(max_length=20, choices=ROLE_CHOICES)
    content = models.TextField()
    tool_calls = models.JSONField(default=list, blank=True)
    sources = models.JSONField(default=list, blank=True)
    token_usage = models.JSONField(default=dict, blank=True)
    latency_ms = models.IntegerField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "ai_messages"
        ordering = ["created_at"]
        indexes = [
            models.Index(fields=["conversation", "created_at"], name="idx_ai_msg_conv_time"),
        ]

    def __str__(self) -> str:
        return f"[{self.role}] {self.content[:40]}..."
